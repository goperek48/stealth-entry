// Level definitions for Nightshade. Maps are ASCII grids, parsed tolerantly:
//   '#' wall   'C' crate (blocks movement and sight)   'B' bush (hides the player)
//   '.' floor  'S' player start   'I' intel shard   'E' exit door
// Rows are padded or trimmed to COLS so a hand-drawn map never breaks the parser.
// Guard patrols are waypoint lists in tile coordinates; a guard starts at [0].
import { COLS, ROWS } from './config.js';

export function parseLevel(def) {
  const walls = new Set();
  const crates = new Set();
  const bushes = new Set();
  const shards = [];
  let start = { x: 1.5, y: 1.5 };
  let exit = { x: COLS - 1.5, y: ROWS - 1.5 };
  const key = (x, y) => x + ',' + y;
  def.map.forEach((rawRow, ty) => {
    const row = (rawRow + '.'.repeat(COLS)).slice(0, COLS);
    for (let tx = 0; tx < COLS; tx++) {
      const ch = row[tx];
      if (ch === '#') walls.add(key(tx, ty));
      else if (ch === 'C') crates.add(key(tx, ty));
      else if (ch === 'B') bushes.add(key(tx, ty));
      else if (ch === 'S') start = { x: tx + 0.5, y: ty + 0.5 };
      else if (ch === 'I') shards.push({ x: tx + 0.5, y: ty + 0.5, taken: false });
      else if (ch === 'E') exit = { x: tx + 0.5, y: ty + 0.5 };
    }
  });
  return {
    name: def.name,
    brief: def.brief,
    walls, crates, bushes, shards, start, exit,
    guards: def.guards.map((g) => ({
      waypoints: g.map(([tx, ty]) => ({ x: tx + 0.5, y: ty + 0.5 })),
    })),
  };
}

